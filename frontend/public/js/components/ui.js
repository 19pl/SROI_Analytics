export const badge = (status, label) => `<span class="badge badge-${status}">${label ?? STATUS_LABEL[status]}</span>`;

export function card({ title = '', description = '', action = '', body = '', cls = '' }) {
  const head = title || action
    ? `<div class="card-head"><div>${title ? `<h2 class="card-title">${title}</h2>` : ''}${description ? `<p class="muted">${description}</p>` : ''}</div>${action}</div>`
    : '';
  return `<section class="card ${cls}">${head}${body}</section>`;
}

export function numberField({ key, label, value, suffix = '', min = 0, max = 1e12, step = 1 }) {
  return `<label class="field"><span class="field-label">${label}</span><span class="field-control">
    <input class="input" type="number" inputmode="decimal" data-field="${key}" value="${value}" min="${min}" max="${max}" step="${step}" />
    <span class="field-suffix">${suffix}</span></span></label>`;
}

export const textField = ({ key, label, value }) =>
  `<label class="field"><span class="field-label">${label}</span><input class="input" data-field="${key}" value="${escapeHtml(value)}" /></label>`;
